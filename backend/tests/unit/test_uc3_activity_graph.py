# AB3.4 — GenerativeAgent.generate
# --------------------------------------------------------------------------- #
def test_ut_3_6_generative_agent_returns_the_draft():
    """UT-3.6: the writer wraps the completion as a GENERATED draft and passes the system prompt
    through — the grounding rules live in that system message, so dropping it un-grounds the model."""
    llm = _FakeLLM()
    agent = GenerativeAgent(llm)

    out = agent.generate("make a rhyming activity", system="SYS")

    assert out == {"content": DRAFT, "status": "GENERATED"}
    assert llm.draft_calls == ["make a rhyming activity"]


@pytest.mark.parametrize("completion", ["", "   ", None])
def test_ut_3_7_an_empty_completion_is_a_failure_not_a_draft(completion):
    """UT-3.7: an empty completion raises rather than returning. Flowing on as `content` it would
    be reviewed and rejected as if the model had written a bad activity, sending a therapist after
    a prompt problem when the LLM edge is what is broken."""
    class _Empty(_FakeLLM):
        def complete(self, prompt, system=None, temperature=None, seed=None):
            return completion

    with pytest.raises(GenerationFailedError):
        GenerativeAgent(_Empty()).generate("prompt")


def test_ut_3_7b_a_transport_failure_is_wrapped():
    """UT-3.7: a raising client surfaces as GenerationFailedError, so callers catch one type
    rather than every exception httpx and the SDKs can throw."""
    class _Boom(_FakeLLM):
        def complete(self, prompt, system=None, temperature=None, seed=None):
            raise TimeoutError("read timeout")

    with pytest.raises(GenerationFailedError):
        GenerativeAgent(_Boom()).generate("prompt")


# --------------------------------------------------------------------------- #
# AB3.5 — ValidativeAgent.validate
# --------------------------------------------------------------------------- #
def test_ut_3_8_passes_a_compliant_activity():
    """UT-3.8: a passing verdict comes back as valid with no notes."""
    llm = _FakeLLM(verdicts=[PASS])

    out = ValidativeAgent(llm).validate({"content": DRAFT}, [], {})

    assert out == {"valid": True, "notes": ""}


def test_ut_3_9_fails_with_actionable_feedback():
    """UT-3.9: a failing verdict carries the notes, because they are the next prompt's payload."""
    llm = _FakeLLM(verdicts=[FAIL])

    out = ValidativeAgent(llm).validate({"content": DRAFT}, [], {})

    assert out["valid"] is False
    assert "step 2 cites a rime" in out["notes"]


def test_the_reviewer_is_shown_the_grounding_it_must_judge_against():
    """Criterion 1 of the framework is "nothing outside the grounding", which is unanswerable
    without the grounding. A reviewer shown only the draft can check that it reads well and
    nothing else — which is the failure the hardcoded `valid: True` stub already was."""
    llm = _FakeLLM(verdicts=[PASS])
    chunk = {"activity_title": "Onset and rime", "content_md": "Clap the onset.",
             "concept": "onset_rime", "stage": "practice",
             "source_file": "2) A1.pdf", "page_start": "14"}

    ValidativeAgent(llm).validate({"content": DRAFT}, [chunk], {"band": "A"})

    sent = llm.review_calls[0]
    assert "Onset and rime" in sent          # the chunk title
    assert "Clap the onset." in sent         # and its actual body, not just a label
    assert DRAFT in sent                     # alongside the draft under review


def test_an_empty_draft_is_rejected_without_calling_the_model():
    """Nothing to review is not a pass, and is not worth an LLM call either."""
    llm = _FakeLLM()

    out = ValidativeAgent(llm).validate({"content": "   "}, [], {})

    assert out["valid"] is False
    assert llm.review_calls == []


# --------------------------------------------------------------------------- #
# parse_verdict — the fail-closed rule
# --------------------------------------------------------------------------- #
@pytest.mark.parametrize("raw", [
    '{"valid": true}',
    '```json\n{"valid": true}\n```',                       # fenced, as models habitually do
    'Here is my verdict:\n{"valid": true}\nHope that helps.',  # padded with prose
])
def test_a_pass_is_read_through_the_wrappers_models_add(raw):
    assert parse_verdict(raw)["valid"] is True


@pytest.mark.parametrize("raw", [
    None, "", "   ",
    "Looks good to me!",                    # prose approval with no JSON at all
    '{"valid": "yes"}',                     # right shape, wrong type
    '{"verdict": true}',                    # wrong key
    '{"valid": true',                       # truncated
])
def test_an_unreadable_verdict_fails_closed(raw):
    """A review that did not happen is not an approval. This is the exact bug the old
    `return {"valid": True}` stub was, so it is asserted rather than assumed."""
    out = parse_verdict(raw)

    assert out["valid"] is False
    assert out["notes"]                     # and it says why, so the retry is informed
